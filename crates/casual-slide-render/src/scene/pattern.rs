#[cfg(test)]
mod tests {
    use super::*;

    fn share(p: P) -> f64 {
        f64::from(bits(p).iter().map(|b| b.count_ones()).sum::<u32>()) / 64.0
    }

    #[test]
    fn percentage_presets_set_close_to_their_share_and_grow_with_it() {
        let pct = [
            (P::Pct5, 0.05),
            (P::Pct10, 0.10),
            (P::Pct20, 0.20),
            (P::Pct25, 0.25),
            (P::Pct30, 0.30),
            (P::Pct40, 0.40),
            (P::Pct50, 0.50),
            (P::Pct60, 0.60),
            (P::Pct70, 0.70),
            (P::Pct75, 0.75),
            (P::Pct80, 0.80),
            (P::Pct90, 0.90),
        ];
        let mut last = 0.0;
        for (p, want) in pct {
            let got = share(p);
            assert!((got - want).abs() <= 0.07, "{p:?}: {got}");
            assert!(got > last, "{p:?} is no darker than the one before");
            last = got;
        }
    }

    #[test]
    fn line_presets_run_the_way_their_names_say() {
        // Horizontal: whole rows. Vertical: one column in every row.
        assert!(bits(P::Horz).iter().all(|r| *r == 0xFF || *r == 0));
        assert!(bits(P::Vert).iter().all(|r| *r == 0x80));
        // Down: each row's set cell one to the right of the row above's.
        let dn = bits(P::LtDnDiag);
        assert!(dn.windows(2).all(|w| w[1] == w[0] >> 1));
        let up = bits(P::LtUpDiag);
        assert!(up.windows(2).all(|w| w[1] == w[0] << 1));
    }
}
