/// A name for a preset no group names: its token in words, "gear6" as "Gear 6".
export function wordsOf(prst) {
  const w = prst.replace(/([a-z])([A-Z0-9])/g, "$1 $2").replace(/([0-9])([A-Za-z])/g, "$1 $2");
  return w.charAt(0).toUpperCase() + w.slice(1);
}

/// The group list with Other Shapes added: every preset in `all` no group names.
export function withOthers(all) {
  const named = new Set(GROUPS.flatMap((grp) => grp.items.map((i) => i.prst)));
  const rest = all.filter((p) => !named.has(p));
  const isLine = (p) => /Connector[0-9]$/.test(p) || p === "lineInv";
  const items = rest.map((p) => g(p, wordsOf(p)));
  for (const i of items) i.line = isLine(i.prst);
  return rest.length ? [...GROUPS, { name: "Other Shapes", items }] : GROUPS;
}
