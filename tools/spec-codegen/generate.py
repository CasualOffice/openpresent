#!/usr/bin/env python3
"""T1K: generate typed values, readers and writers for SmartArt, equations and ink.

    python3 tools/spec-codegen/generate.py           # write the files
    python3 tools/spec-codegen/generate.py --check   # fail if they are not what it writes

From schema_parts.py's reading of the schemas it writes, for `diagram`, `math` and `ink`:

  crates/casual-slide-model/src/<module>/schema.rs    a struct per type, an enum per simple type
  crates/casual-slide-import/src/<module>/schema.rs   a reader per type
  crates/casual-slide-export/src/<module>/schema.rs   a patcher per type

Each generated reader says what owns the names it reads (`// spec-audit: owner=`), so
tools/spec-audit holds it to the same bar as hand-written code. What it writes is held by
behaviour, not by this file: crates/casual-slide-export/tests/graphics.rs walks every row
of DGM, MATH and INK against real fixtures and sees each one read, written and validated.

Types of other tiers (a shape's properties, a text body, a colour) are taken from those
tiers through FOREIGN, by hand-written functions in each crate's src/diagram.rs. Nothing
in this file invents semantics: an element named here reads and writes as its schema says.
"""
