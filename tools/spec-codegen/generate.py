RUST_WORDS = set("""as async await break const continue crate dyn else enum extern false fn for if impl in let
    loop match mod move mut pub ref return self static struct super trait true type unsafe use where while
    abstract become box do final macro override priv typeof unsized virtual yield try gen""".split())

HEADER = "// @generated by tools/spec-codegen/generate.py. Do not edit.\n"


def snake(name):
    name = name.split(":")[-1]
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", s).lower()
    s = re.sub(r"[^a-z0-9_]", "_", s)
    if s in RUST_WORDS or s[:1].isdigit():
        s += "_"
    return s


def pascal(name):
    parts = re.split(r"[^A-Za-z0-9]+", name)
    s = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not s:
        s = "Empty"
    if s[0].isdigit():
        s = "V" + s
    return "SelfValue" if s == "Self" else s


class Names:
    """Rust names for one module's types."""

    def __init__(self, schemas, module):
        self.s, self.module = schemas, module
        self.structs, self.enums = {}, {}
        used = set()
        for t in schemas.module_types(module):
            name = t.tag + pascal(re.sub(r"^CT_", "", t.name))
            while name in used or name in ("Box", "Vec", "Option", "String", "Root"):
                name += "Type"
            used.add(name)
            self.structs[(t.ns, t.name)] = name
        for st in schemas.module_simples(module):
            name = st.tag + pascal(re.sub(r"^ST_", "", st.name))
            while name in used:
                name += "Kind"
            used.add(name)
            self.enums[(st.ns, st.name)] = name

    def struct(self, key):
        return self.structs[key]

    def field(self, child_or_attr):
        return snake(getattr(child_or_attr, "local"))


def st_info(names, key):
    """What a simple type is in Rust: (type, range check, member check needed).
    `member` is true when its values reach the file through a union or a list."""
    s = names.s
    if key is None:
        return "String", None, False
    ns, local = key
    if ns == sp.XSD:
        return sp.SCALARS.get(local, "String"), None, False
    st = s.simples.get(key)
    if st is None:
        return "String", None, False
    if st.union is not None:
        return "String", None, True
    if st.list is not None:
        item, _, _ = st_info(names, st.list)
        return f"XmlList<{item}>", None, bool(has_values(s, st.list))
    if st.values:
        return f"{enum_path(names, key)}", None, False
    if st.base:
        base, _, _ = st_info(names, st.base)
        check = None
        if st.min is not None or st.max is not None:
            low = f"{st.min}" if st.min is not None else ""
            high = f"={st.max}" if st.max is not None else ""
            check = f"{low}..{high}"
        return base, check, False
    return "String", None, False


def enum_path(names, key):
    if key in names.enums:
        return names.enums[key]
    for module in sp.SOURCES:
        other = Names(names.s, module)
        if key in other.enums:
            return f"crate::{module}::schema::{other.enums[key]}"
    raise SystemExit(f"no enum for {key}")


def has_values(s, key):
    st = s.simples.get(key)
    if st is None:
        return False
    return bool(st.values) or (st.list and has_values(s, st.list)) or any(has_values(s, m) for m in st.union or [])


def member_values(s, key, seen=None):
    """Every enumerated token a union or list may spell."""
    seen = seen if seen is not None else set()
    st = s.simples.get(key)
    if st is None or key in seen:
        return []
    seen.add(key)
    out = list(st.values)
    if st.list:
        out += member_values(s, st.list, seen)
    for m in st.union or []:
        out += member_values(s, m, seen)
    return out


def open_members(s, key, seen=None):
    """Whether a union admits anything beyond its enumerations, and by what check."""
    seen = seen if seen is not None else set()
    st = s.simples.get(key)
    if st is None:
        return {"any"} if key[0] != sp.XSD or sp.SCALARS.get(key[1], "String") == "String" else {sp.SCALARS[key[1]]}
    if key in seen:
        return set()
    seen.add(key)
    if st.union is not None:
        return set().union(*[open_members(s, m, seen) for m in st.union]) if st.union else set()
    if st.list is not None:
        return open_members(s, st.list, seen)
    if st.values:
        return set()
    if st.base:
        return open_members(s, st.base, seen)
    return {"any"}


class Module:
    def __init__(self, schemas, module, audit_schema, keys):
        self.s, self.module = schemas, module
        self.names = Names(schemas, module)
        self.types = schemas.module_types(module)
        self.simples = schemas.module_simples(module)
        self.roots = schemas.module_roots(module)
        self.audit, self.keys = audit_schema, keys
        self.member_fns = {}
        for t in self.types:
            for a in t.attrs:
                _, _, member = st_info(self.names, a.st)
                if member:
                    self.member_fns.setdefault(a.st, set()).add(a.local)

    # ---- shared
    def kind_of(self, child):
        if child.type in FOREIGN:
            return "foreign"
        if child.type in self.s.types:
            return "complex"
        return "simple"

    def rust_of(self, child):
        kind = self.kind_of(child)
        if kind == "foreign":
            return FOREIGN[child.type][0]
        if kind == "complex":
            return self.struct_path(child.type)
        return st_info(self.names, child.type)[0]

    def struct_path(self, key):
        if key in self.names.structs:
            return self.names.structs[key]
        raise SystemExit(f"{self.module}: no struct for {key}")

    def groups(self, t):
        return [FOREIGN_GROUPS[g] for g, _ in t.retained_groups if g in FOREIGN_GROUPS]

    def overlays(self, t):
        return OVERLAYS.get((t.ns, t.name), [])

    def items(self, t):
        return [c for c in t.children if c.in_items]

    def plain(self, t):
        return [c for c in t.children if not c.in_items]

    def item_enum(self, t):
        return self.names.struct((t.ns, t.name)) + "Item"

    def variant(self, c, t):
        same = [x for x in self.items(t) if x.local == c.local]
        return pascal(c.local) + ("" if len(same) == 1 or c is same[0] else "Other")

    def fields(self, t):
        """Field names, unique within a struct."""
        out = {}
        used = set()
        for a in t.attrs:
            name = snake(a.local)
            while name in used:
                name += "_attr"
            used.add(name)
            out[id(a)] = name
        for c in self.plain(t):
            name = snake(c.local)
            while name in used:
                name += "_el"
            used.add(name)
            out[id(c)] = name
        return out

    def ns_const(self, ns):
        return "NS_" + self.s.prefix_of.get(ns, "other").upper()

    def owner_comment(self, t):
        key = self.keys.get(t.ns)
        hosts = self.audit.hosts.get((key, t.name), ()) if key else ()
        names = sorted({local for _, local in hosts})
        return f"// spec-audit: owner={','.join(names)}\n" if names else ""

    def order(self, t):
        return [c.local for c in t.children]

    def fn_read(self, key):
        return "read_" + snake(self.names.struct(key))

    def fn_patch(self, key):
        return "patch_" + snake(self.names.struct(key))

    def root_rows(self):
        out = []
        for (ns, name), typ in self.roots:
            key = self.keys.get(ns)
            out.append((ns, name, typ, f"{key}:<{name}>" if key else None))
        return out

    # ---- model
    def model(self):
        out = [HEADER, f"//! `{self.module}`: every type of its schema, as plain typed values. See `tools/spec-codegen`.\n\n"]
        out.append("use crate::properties::token_enum;\n")
        if self.module == "diagram":
            out.append("use crate::color::Color;\nuse crate::d3::{Scene3D, Shape3D};\nuse crate::shape::Transform;\n"
                       "use crate::text::{Text3D, TextBody, TextListStyle};\nuse crate::theme::ShapeStyle;\n"
                       "use crate::diagram::{DrawingIdentity, Extensions, Formatting, NvGroupProps, NvShapeProps, ShapeProps, XmlList};\n")
            out.append("use crate::properties::Float64;\n")
        elif self.module == "math":
            out.append("use crate::text::CharacterProperties;\n")
        else:
            out.append("use crate::diagram::XmlList;\n")
        out.append("\n")
        for st in self.simples:
            if not st.values or st.union is not None:
                continue
            name = self.names.enums[(st.ns, st.name)]
            prefix = self.s.prefix_of[st.ns]
            variants, seen = [], {}
            for v in st.values:
                var = pascal(v)
                n = seen.get(var.lower(), 0)
                seen[var.lower()] = n + 1
                if n:
                    var += str(n + 1)
                variants.append(f'        {var} = "{v}",\n')
            out.append(f"token_enum!(\n    /// `{prefix}:{st.name}`.\n    {name} {{\n{''.join(variants)}    }}\n);\n\n")
        for t in self.types:
            name = self.names.struct((t.ns, t.name))
            prefix = t.prefix
            fields = self.fields(t)
            also = "".join(f" Includes `{g}`." for g in sorted(set(t.included)))
            out.append(f"/// `{prefix}:{t.name}`.{also}\n#[derive(Debug, Clone, Default, PartialEq, Eq)]\npub struct {name} {{\n")
            for a in t.attrs:
                rust = st_info(self.names, a.st)[0]
                out.append(f"    /// `@{a.local}`.\n    pub {fields[id(a)]}: Option<{rust}>,\n")
            if t.text is not None:
                rust = st_info(self.names, t.text)[0]
                out.append(f"    /// The element's text.\n    pub text: Option<{rust}>,\n")
            for c in self.plain(t):
                rust = self.rust_of(c)
                if c.repeats:
                    out.append(f"    /// `{c.local}`.\n    pub {fields[id(c)]}: Vec<{rust}>,\n")
                elif self.kind_of(c) == "simple":
                    out.append(f"    /// `{c.local}`.\n    pub {fields[id(c)]}: Option<{rust}>,\n")
                else:
                    out.append(f"    /// `{c.local}`.\n    pub {fields[id(c)]}: Option<Box<{rust}>>,\n")
            for field, _, local, foreign in self.overlays(t):
                out.append(f"    /// `a:{local}`, which Office writes here for DrawingML text.\n    pub {field}: Option<Box<{foreign[0]}>>,\n")
            for field, rust, many, *_ in self.groups(t):
                wrapped = f"Vec<{rust}>" if many else f"Option<{rust}>"
                out.append(f"    /// `{field}`, a group of another tier.\n    pub {field}: {wrapped},\n")
            if self.items(t):
                out.append(f"    /// The repeating choice, in file order.\n    pub items: Vec<{self.item_enum(t)}>,\n")
            out.append("}\n\n")
            if self.items(t):
                out.append(f"/// One child of `{prefix}:{t.name}`'s repeating choice.{also}\n#[derive(Debug, Clone, PartialEq, Eq)]\npub enum {self.item_enum(t)} {{\n")
                for c in self.items(t):
                    var = self.variant(c, t)
                    rust = self.rust_of(c)
                    inner = rust if self.kind_of(c) == "simple" else f"Box<{rust}>"
                    out.append(f"    /// `{c.local}`.\n    {var}({inner}),\n")
                out.append("}\n\n")
        out.append(f"/// A part or element of `{self.module}` that can stand alone, by its root.\n#[derive(Debug, Clone, PartialEq, Eq)]\npub enum Root {{\n")
        for ns, name, typ, _ in self.root_rows():
            out.append(f"    /// `{self.s.prefix_of[ns]}:{name}`.\n    {self.root_variant(ns, name)}(Box<{self.root_type(typ)}>),\n")
        out.append("}\n")
        return "".join(out)

    def root_variant(self, ns, name):
        return self.s.tag_of[ns] + pascal(name)

    def root_type(self, typ):
        if typ in FOREIGN:
            return FOREIGN[typ][0]
        return self.struct_path(typ)

    # ---- import
    def reader(self):
        out = [HEADER, f"//! Read `{self.module}` from a tree, element by element. See `tools/spec-codegen`.\n\n"]
        out.append("use casual_slide_import_prelude::*;\n".replace("casual_slide_import_prelude", "crate::diagram::prelude"))
        out.append(f"use casual_slide_model::{self.module}::schema as m;\n\n")
        for ns, const in self.ns_consts():
            out.append(const)
        for st, attrs in sorted(self.member_fns.items()):
            out.append(self.member_fn(st, attrs))
        for t in self.types:
            out.append(self.read_type(t))
        out.append(self.read_root())
        return "".join(out)

    def ns_consts(self):
        seen = {}
        namespaces = [ns for _, ns, _, _ in sp.SOURCES[self.module]]
        for t in self.types:
            for c in t.children:
                if c.ns not in namespaces:
                    namespaces.append(c.ns)
        for ns in namespaces:
            if ns == DML or ns in seen:
                continue
            uris = [ns] + ([sp.STRICT[ns]] if ns in sp.STRICT else [])
            body = ", ".join(f'"{u}"' for u in uris)
            seen[ns] = f"/// `{self.s.prefix_of.get(ns, ns)}:`.\npub const {self.ns_const(ns)}: &[&str] = &[{body}];\n\n"
        return list(seen.items())

    def member_fn(self, st, attrs):
        s = self.s
        tests = " || ".join(f'attribute == "{a}"' for a in sorted(attrs))
        values = sorted(set(member_values(s, st)))
        extra = open_members(s, st)
        checks = []
        if values:
            checks.append("matches!(value, " + " | ".join(f'"{v}"' for v in values) + ")")
        for kind in sorted(extra):
            if kind == "any":
                checks.append("true")
            elif kind == "bool":
                checks.append("bool::parse_lexical(value).is_some()")
            else:
                checks.append(f"{kind}::parse_lexical(value).is_some()")
        body = " || ".join(checks) or "false"
        return (f"/// What `{st[1]}` admits, on the attributes that hold it.\n"
                f"pub(crate) fn member_{snake(st[1])}(attribute: &str, value: &str) -> bool {{\n"
                f"    ({tests}) && ({body})\n}}\n\n")

    def read_type(self, t):
        key = (t.ns, t.name)
        name = self.names.struct(key)
        fields = self.fields(t)
        out = [self.owner_comment(t)]
        out.append(f"pub(crate) fn {self.fn_read(key)}(c: &mut SchemaReader<'_, '_>, el: &Elem) -> Res<m::{name}> {{\n")
        if key in CHARGED:
            out.append(f"    c.charge(GraphicBound::{CHARGED[key]})?;\n")
        out.append("    c.enter()?;\n    let mut e = el.clone();\n" if t.attrs else "    c.enter()?;\n    let e = el.clone();\n")
        out.append(f"    let mut out = m::{name}::default();\n")
        for a in t.attrs:
            rust, check, member = st_info(self.names, a.st)
            f = fields[id(a)]
            if a.qualified:
                out.append(f'    let name = c.attr_name(&e, {self.ns_const(t.ns)}, "{a.local}");\n')
            label = "&name" if a.qualified else f'"{a.name}"'
            if a.rel:
                out.append(f'    out.{f} = c.rel_attr(&mut e, "{a.local}");\n')
            elif member:
                out.append(f'    out.{f} = c.attr_member(&mut e, {label if a.qualified else chr(34) + a.local + chr(34)}, {"true" if a.required else "false"}, member_{snake(a.st[1])})?;\n')
            elif check:
                out.append(f'    out.{f} = c.attr_range(&mut e, {label}, {"true" if a.required else "false"}, {check})?;\n')
            elif a.required:
                out.append(f'    out.{f} = c.attr_required(&mut e, {label})?;\n')
            else:
                out.append(f'    out.{f} = c.attr(&mut e, {label})?;\n')
        out.append("    c.finish(&e);\n")
        if t.text is not None:
            out.append("    out.text = c.text(&e)?;\n")
        by_ns = {}
        for c in t.children:
            by_ns.setdefault(c.ns, []).append(c)
        overlays = self.overlays(t)
        groups = self.groups(t)
        if by_ns or overlays or groups or t.text is None:
            if t.text is None:
                out.append("    for child in c.children(&e)? {\n")
                for ns, kids in by_ns.items():
                    const = "ns::DML" if ns == DML else self.ns_const(ns)
                    out.append(f"        if child.in_namespace({const}) {{\n            match child.local.as_str() {{\n")
                    for ch in kids:
                        out.append(self.read_arm(t, ch, fields))
                    if ns == DML:
                        for field, _, local, foreign in overlays:
                            out.append(self.overlay_arm(field, local, foreign))
                    out.append("                _ => {}\n            }\n        }\n")
                if DML not in by_ns and overlays:
                    out.append("        if child.in_namespace(ns::DML) {\n            match child.local.as_str() {\n")
                    for field, _, local, foreign in overlays:
                        out.append(self.overlay_arm(field, local, foreign))
                    out.append("                _ => {}\n            }\n        }\n")
                for field, rust, many, test, read, _ in groups:
                    if many:
                        out.append(f"        if {test}(c, &child) {{\n            if let Some(v) = {read}(c, &child)? {{\n                out.{field}.push(v);\n            }}\n            continue;\n        }}\n")
                    else:
                        out.append(f"        if {test}(c, &child) {{\n            if out.{field}.is_some() {{\n                c.duplicate(&child);\n            }} else {{\n                out.{field} = {read}(c, &child)?;\n            }}\n            continue;\n        }}\n")
                out.append("        c.retained(&child);\n    }\n")
        out.append("    c.leave();\n    Ok(out)\n}\n\n")
        return "".join(out)

    def overlay_arm(self, field, local, foreign):
        return (f'                "{local}" => {{\n                    if out.{field}.is_some() {{\n                        c.duplicate(&child);\n                    }} else {{\n'
                f'                        out.{field} = Some(Box::new({foreign[1]}(c, &child)?));\n                    }}\n                    continue;\n                }}\n')

    def read_call(self, ch):
        kind = self.kind_of(ch)
        if kind == "foreign":
            return f"{FOREIGN[ch.type][1]}(c, &child)?"
        if kind == "complex":
            return f"{self.fn_read(ch.type)}(c, &child)?"
        return "c.typed(&child)?"

    def read_arm(self, t, ch, fields):
        call = self.read_call(ch)
        kind = self.kind_of(ch)
        if ch.in_items:
            enum = self.item_enum(t)
            var = self.variant(ch, t)
            if kind == "simple":
                return (f'                "{ch.local}" => {{\n                    if let Some(v) = {call} {{\n'
                        f'                        out.items.push(m::{enum}::{var}(v));\n                    }}\n                    continue;\n                }}\n')
            return f'                "{ch.local}" => {{\n                    out.items.push(m::{enum}::{var}(Box::new({call})));\n                    continue;\n                }}\n'
        f = fields[id(ch)]
        if ch.repeats:
            if kind == "simple":
                return (f'                "{ch.local}" => {{\n                    if let Some(v) = {call} {{\n'
                        f'                        out.{f}.push(v);\n                    }}\n                    continue;\n                }}\n')
            return f'                "{ch.local}" => {{\n                    out.{f}.push({call});\n                    continue;\n                }}\n'
        value = call if kind == "simple" else f"Some(Box::new({call}))"
        return (f'                "{ch.local}" => {{\n                    if out.{f}.is_some() {{\n                        c.duplicate(&child);\n                    }} else {{\n'
                f'                        out.{f} = {value};\n                    }}\n                    continue;\n                }}\n')

    def read_root(self):
        out = [f"/// Read a standalone element of `{self.module}`, by its root. `None` if it is none of them.\n"]
        for ns, name, typ, row in self.root_rows():
            if row:
                out.append(f"// spec-audit: {row}\n")
        out.append("pub(crate) fn read_root(c: &mut SchemaReader<'_, '_>, el: &Elem) -> Res<Option<m::Root>> {\n")
        for ns, name, typ, _ in self.root_rows():
            const = self.ns_const(ns)
            call = f"{FOREIGN[typ][1]}(c, el)?" if typ in FOREIGN else f"{self.fn_read(typ)}(c, el)?"
            out.append(f'    if el.is({const}, "{name}") {{\n        return Ok(Some(m::Root::{self.root_variant(ns, name)}(Box::new({call}))));\n    }}\n')
        out.append("    Ok(None)\n}\n\n")
        out.append(f"/// Whether an element is one that [`read_root`] reads.\npub fn is_root(el: &Elem) -> bool {{\n")
        tests = " || ".join(f'el.is({self.ns_const(ns)}, "{name}")' for ns, name, _, _ in self.root_rows())
        out.append(f"    {tests or 'false'}\n}}\n")
        return "".join(out)

    # ---- export
    def writer(self):
        out = [HEADER, f"//! Patch `{self.module}` in a tree, node by node. See `tools/spec-codegen`.\n\n"]
        out.append("use crate::diagram::prelude::*;\n")
        out.append(f"use casual_slide_model::{self.module}::schema as m;\n")
        out.append(f"use casual_slide_import::{self.module}::schema as read;\n\n")
        used = {c.ns for t in self.types for c in t.children} | {k[0] for k, _ in self.roots}
        for ns, _ in self.ns_consts():
            if ns in used:
                out.append(f"const {self.ns_const(ns)}: &[&str] = read::{self.ns_const(ns)};\n")
        out.append("\n")
        for st, attrs in sorted(self.member_fns.items()):
            out.append(self.member_fn(st, attrs))
        for t in self.types:
            out.append(self.patch_type(t))
        out.append(self.patch_root())
        return "".join(out)

    def patch_type(self, t):
        key = (t.ns, t.name)
        name = self.names.struct(key)
        fields = self.fields(t)
        out = [self.owner_comment(t)]
        out.append(f"pub(crate) fn {self.fn_patch(key)}(w: &mut Writer<'_>, el: &Elem, b: Option<&m::{name}>, a: &m::{name}) -> R {{\n")
        order = self.order(t)
        if order or self.overlays(t):
            items = ", ".join(f'"{o}"' for o in order)
            out.append(f"    const ORDER: &[&str] = &[{items}];\n")
        else:
            out.append("    let _ = (&w, &el);\n" if not t.attrs and t.text is None and not self.groups(t) else "")
        for at in t.attrs:
            f = fields[id(at)]
            _, _, member = st_info(self.names, at.st)
            pair = f"b.and_then(|b| b.{f}.as_ref()), a.{f}.as_ref()"
            if at.qualified:
                prefix = self.s.prefix_of[t.ns]
                out.append(f'    let name = attr_name(w, el, {self.ns_const(t.ns)}, "{prefix}", "{at.local}", a.{f}.is_some())?;\n')
                if member:
                    out.append(f'    attr_member(w, el, &name, {pair}, member_{snake(at.st[1])})?;\n')
                else:
                    out.append(f'    w.attr(el, &name, {pair})?;\n')
            elif at.rel:
                out.append(f'    rel_attr_named(w, el, "{at.local}", {pair})?;\n')
            elif member:
                out.append(f'    attr_member(w, el, "{at.local}", {pair}, member_{snake(at.st[1])})?;\n')
            else:
                out.append(f'    w.attr(el, "{at.name}", {pair})?;\n')
        if t.text is not None:
            out.append("    sync_own_text(w, el, b.and_then(|b| b.text.as_ref()), a.text.as_ref())?;\n")
        for c in self.plain(t):
            out.append(self.patch_plain(t, c, fields))
        for field, _, local, foreign in self.overlays(t):
            out.append(f'    w.sync_child(el, ns::DML, "a", ORDER, "{local}", b.and_then(|b| b.{field}.as_deref()), a.{field}.as_deref(), {foreign[2]})?;\n')
        for field, rust, many, test, read, patch in self.groups(t):
            if many:
                out.append(f'    {patch}(w, el, b.map_or(&[], |b| b.{field}.as_slice()), &a.{field})?;\n')
            else:
                out.append(f'    {patch}(w, el, b.and_then(|b| b.{field}.as_ref()), a.{field}.as_ref())?;\n')
        if self.items(t):
            enum = self.item_enum(t)
            names = ", ".join(self.item_name(c) for c in self.items(t))
            out.append(f"    sync_items(w, el, ORDER, &[{names}], b.map_or(&[], |b| b.items.as_slice()), &a.items, {snake(enum)}_name, patch_{snake(enum)})?;\n")
        out.append("    let _ = (&b, &a);\n    Ok(())\n}\n\n")
        if self.items(t):
            out.append(self.patch_items_fn(t))
        return "".join(out)

    def item_name(self, c):
        const = "ns::DML" if c.ns == DML else self.ns_const(c.ns)
        return f'({const}, "{self.s.prefix_of.get(c.ns, "a")}", "{c.local}")'

    def patch_items_fn(self, t):
        enum = self.item_enum(t)
        out = [f"fn {snake(enum)}_name(i: &m::{enum}) -> (&'static [&'static str], &'static str, &'static str) {{\n    match i {{\n"]
        for c in self.items(t):
            out.append(f"        m::{enum}::{self.variant(c, t)}(_) => {self.item_name(c)},\n")
        out.append("    }\n}\n\n")
        out.append(self.owner_comment(t))
        out.append(f"fn patch_{snake(enum)}(w: &mut Writer<'_>, el: &Elem, b: Option<&m::{enum}>, a: &m::{enum}) -> R {{\n    match a {{\n")
        for c in self.items(t):
            var = self.variant(c, t)
            kind = self.kind_of(c)
            if kind == "simple":
                out.append(f"        m::{enum}::{var}(v) => set_lexical(w, el, v),\n")
                continue
            patch = FOREIGN[c.type][2] if kind == "foreign" else self.fn_patch(c.type)
            out.append(f"        m::{enum}::{var}(a) => {patch}(w, el, match b {{ Some(m::{enum}::{var}(b)) => Some(&**b), _ => None }}, a),\n")
        out.append("    }\n}\n\n")
        return "".join(out)

    def patch_plain(self, t, c, fields):
        f = fields[id(c)]
        kind = self.kind_of(c)
        const = "ns::DML" if c.ns == DML else self.ns_const(c.ns)
        prefix = self.s.prefix_of.get(c.ns, "a")
        if kind == "simple":
            if c.repeats:
                return (f'    sync_many(w, el, {const}, "{prefix}", ORDER, "{c.local}", b.map_or(&[], |b| b.{f}.as_slice()), &a.{f}, '
                        f'|w, el, _, v| set_lexical(w, el, v))?;\n')
            return f'    w.sync_child(el, {const}, "{prefix}", ORDER, "{c.local}", b.and_then(|b| b.{f}.as_ref()), a.{f}.as_ref(), |w, el, _, v| set_lexical(w, el, v))?;\n'
        patch = FOREIGN[c.type][2] if kind == "foreign" else self.fn_patch(c.type)
        if c.repeats:
            return f'    sync_many(w, el, {const}, "{prefix}", ORDER, "{c.local}", b.map_or(&[], |b| b.{f}.as_slice()), &a.{f}, {patch})?;\n'
        return f'    w.sync_child(el, {const}, "{prefix}", ORDER, "{c.local}", b.and_then(|b| b.{f}.as_deref()), a.{f}.as_deref(), {patch})?;\n'

    def patch_root(self):
        out = [f"/// Bring a standalone element of `{self.module}` from one state to another.\n"]
        for ns, name, typ, row in self.root_rows():
            if row:
                out.append(f"// spec-audit: {row}\n")
        out.append("pub(crate) fn patch_root(w: &mut Writer<'_>, el: &Elem, b: Option<&m::Root>, a: &m::Root) -> R {\n    match a {\n")
        for ns, name, typ, _ in self.root_rows():
            var = self.root_variant(ns, name)
            patch = FOREIGN[typ][2] if typ in FOREIGN else self.fn_patch(typ)
            out.append(f"        m::Root::{var}(a) => {patch}(w, el, match b {{ Some(m::Root::{var}(b)) => Some(&**b), _ => None }}, a),\n")
        out.append("    }\n}\n")
        if self.module != "diagram":
            return "".join(out)
        out.append("\n/// The element a root is: its namespaces, preferred prefix and local name.\n")
        out.append("pub(crate) fn root_name(r: &m::Root) -> (&'static [&'static str], &'static str, &'static str) {\n    match r {\n")
        for ns, name, typ, _ in self.root_rows():
            out.append(f'        m::Root::{self.root_variant(ns, name)}(_) => ({self.ns_const(ns)}, "{self.s.prefix_of[ns]}", "{name}"),\n')
        out.append("    }\n}\n")
        return "".join(out)


def rustfmt(text):
    edition = "2024"
    run = subprocess.run(["rustfmt", f"--edition={edition}", "--emit=stdout"], input=text.encode(), capture_output=True, check=False)
    if run.returncode:
        raise SystemExit(f"rustfmt failed:\n{run.stderr.decode()[:4000]}\n{text[:400]}")
    return run.stdout.decode()


def outputs():
    schemas = sp.Schemas()
    audit_schema = audit.Schema(ROOT)
    keys = {v: k for k, v in audit_schema.ns_of_key.items()}
    out = {}
    for module in sp.SOURCES:
        m = Module(schemas, module, audit_schema, keys)
        out[f"crates/casual-slide-model/src/{module}/schema.rs"] = m.model()
        out[f"crates/casual-slide-import/src/{module}/schema.rs"] = m.reader()
        out[f"crates/casual-slide-export/src/{module}/schema.rs"] = m.writer()
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bad = []
    for rel, text in outputs().items():
        text = rustfmt(text)
        path = ROOT / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf8") != text:
                bad.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf8")
    if bad:
        print("out of date, run tools/spec-codegen/generate.py:", *bad, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
